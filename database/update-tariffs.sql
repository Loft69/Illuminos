-- =========================================================
-- Мини-миграция: обновление тарифов без пересоздания БД.
-- Выполнить в PhpMyAdmin, если БД illuminos уже импортирована.
-- =========================================================
USE illuminos;

-- 1) Старый «Базовый» (SD, 299) переименовываем в новый дешёвый «Старт»
UPDATE tariffs
SET name = 'Старт',
    price = 199.00,
    description = 'SD 480p на смартфоне, 1 экран, 10 часов в месяц, реклама перед сеансом'
WHERE name = 'Базовый' AND price = 299.00;

-- 2) Добавляем «Старт», если его ещё нет
INSERT INTO tariffs (name, price, duration_days, description)
SELECT 'Старт', 199.00, 30, 'SD 480p на смартфоне, 1 экран, 10 часов в месяц, реклама перед сеансом'
WHERE NOT EXISTS (SELECT 1 FROM tariffs WHERE name = 'Старт');

-- 3) Добавляем «Базовый» в новом виде (HD, без рекламы)
INSERT INTO tariffs (name, price, duration_days, description)
SELECT 'Базовый', 299.00, 30, 'HD 720p, 1 устройство, без лимита времени, без рекламы, избранное и история'
WHERE NOT EXISTS (SELECT 1 FROM tariffs WHERE name = 'Базовый');

-- 4) Обновляем описания остальных тарифов
UPDATE tariffs SET description = 'Full HD 1080p, 2 устройства одновременно, без рекламы, скачивание на 1 устройство, персональные рекомендации' WHERE name = 'Стандарт';
UPDATE tariffs SET description = '4K HDR + Dolby Atmos, 4 устройства одновременно, скачивание на 4 устройства, ранний доступ к новинкам, пространственный звук' WHERE name = 'Премиум';

